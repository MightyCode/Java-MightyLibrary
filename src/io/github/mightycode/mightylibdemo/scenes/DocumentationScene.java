package io.github.mightycode.mightylibdemo.scenes;

import io.github.mightycode.mightylib.graphics.renderer._2D.shape.RectangleRenderer;
import io.github.mightycode.mightylib.graphics.text.ETextAlignment;
import io.github.mightycode.mightylib.graphics.text.Text;
import io.github.mightycode.mightylib.physics.tweenings.ETweeningBehaviour;
import io.github.mightycode.mightylib.physics.tweenings.ETweeningOption;
import io.github.mightycode.mightylib.physics.tweenings.ETweeningType;
import io.github.mightycode.mightylib.physics.tweenings.type.FloatTweening;
import io.github.mightycode.mightylib.resources.data.JSONFile;
import io.github.mightycode.mightylib.resources.texture.TextureData;
import io.github.mightycode.mightylib.scenes.Scene;
import io.github.mightycode.mightylib.utils.math.MightyMath;
import io.github.mightycode.mightylib.utils.math.color.Color4f;
import io.github.mightycode.mightylib.utils.math.geometry.EDirection;
import io.github.mightycode.mightylibdemo.main.ActionId;
import org.joml.Vector2f;
import org.json.JSONArray;
import org.json.JSONObject;

import java.awt.Color;
import java.awt.GradientPaint;
import java.awt.Graphics2D;
import java.awt.image.BufferedImage;
import java.util.ArrayList;
import java.util.List;

/**
 * Reference scene: a small but complete scene whose comments explain the life of a scene and of its resources.
 * Read it from top to bottom, the methods are in the order the engine calls them:
 *
 *   constructor  -> getInvolvedBatch -> init -> (loading scene displayed while the batches load)
 *   -> launch -> loop of update / postUpdate / display -> unload -> release
 *
 * It uses three kinds of resources:
 *   - a JSON file read from the disk, resources/data/documentationScene.json, declared in the batch
 *     resources/batchs/documentation.batch: the scene is configured by data, not by code;
 *   - a texture of the project, "painting", declared in the same batch;
 *   - a texture generated by the code in init, added to Resources by the scene, deleted in release.
 *
 * Open it with the command "scene DocumentationScene" (console or tools/scenario.py).
 */
public class DocumentationScene extends Scene {
    // Name of the texture created by this scene: resource names must be unique by type in the whole game,
    // so a name owned by a scene is better prefixed with the scene name
    private static final String GENERATED_TEXTURE = "documentationGenerated";
    private static final int GENERATED_TEXTURE_SIZE = 256;

    // Objects created in launch and freed in unload. They are null while the scene loads:
    // a method that can run before launch (release, for example) must not use them.
    private Text title;
    private Text message;
    private final List<RectangleRenderer> squares = new ArrayList<>();
    private FloatTweening rotation;
    private boolean rotationPaused;

    /*
     * Constructor: called by the code that asks for the scene, e.g. new DocumentationScene() in MenuScene.
     * The scene is not active yet and the previous scene is still displayed:
     * only store parameters here, never load or create GL objects.
     * The parent constructor already gives access to resources, glResources, shaderManager and mainContext.
     */
    public DocumentationScene() {
        super();
    }

    /*
     * Batches needed by the scene: names of files in resources/batchs/, without the extension.
     * Before init, the engine adds a reference to each resource of these batches; the resources not loaded yet
     * are read by the workers while the loading scene is displayed. When the scene is left, the engine removes
     * these references: a resource is unloaded only when no batch or other owner references it anymore.
     * So "painting", also in the batch "init" loaded at start, stays loaded when this scene is left,
     * while "documentationScene" is unloaded.
     */
    @Override
    protected String[] getInvolvedBatch() {
        return new String[]{ "documentation" };
    }

    /*
     * First step, called when the scene becomes the current one, while its batches start to load.
     * The resources of the batches are NOT available yet, the cameras and the virtual scene do not exist:
     * declare here what the scene needs in addition to its batches (resources created by code), nothing else.
     * No need to call super.init.
     *
     * Everything added here must be freed in release(), not in unload(): if the player leaves the scene
     * while it is still loading, launch and unload are never called, but release always is.
     */
    @Override
    public void init(String[] args) {
        // A texture computed by code instead of being read from a file. The image is filled here (fast with Java2D),
        // then the engine converts it and sends it to the GPU with the time left in each frame.
        BufferedImage image = new BufferedImage(GENERATED_TEXTURE_SIZE, GENERATED_TEXTURE_SIZE, BufferedImage.TYPE_INT_ARGB);
        Graphics2D graphics = image.createGraphics();
        graphics.setPaint(new GradientPaint(0, 0, new Color(80, 200, 255),
                GENERATED_TEXTURE_SIZE, GENERATED_TEXTURE_SIZE, new Color(160, 60, 200)));
        graphics.fillRect(0, 0, GENERATED_TEXTURE_SIZE, GENERATED_TEXTURE_SIZE);
        graphics.setColor(Color.WHITE);
        graphics.fillOval(GENERATED_TEXTURE_SIZE / 4, GENERATED_TEXTURE_SIZE / 4, GENERATED_TEXTURE_SIZE / 2, GENERATED_TEXTURE_SIZE / 2);
        graphics.dispose();

        // "generated": the data has no file, it can't be read again from the disk (reloadAllOfType skips it)
        TextureData data = new TextureData(GENERATED_TEXTURE, "generated");
        data.setBufferedImage(image);
        data.setPreloaded();

        // Adds the reference "manually": the data stays loaded until deleteResource in release()
        resources.addPreLoadedResource(data);
    }

    /*
     * Second step, called once every resource of the batches and of init is loaded (CPU side).
     * The cameras (main2DCamera, main3DCamera) and the virtual scene exist: create here the renderers, texts
     * and other objects displayed. Their GL objects are sent to the GPU over the next frames, the loading scene
     * stays displayed until they are all sent: the first frame of the scene is complete.
     * No need to call super.launch.
     */
    @Override
    public void launch(String[] args) {
        // The configuration comes from the JSON resource of the batch: change the file, not the code
        JSONObject config = resources.getResource(JSONFile.class, "documentationScene").getObject();

        JSONArray background = config.getJSONArray("backgroundColor");
        // The clear color is kept by the scene and applied before each of its frames
        setClearColor(background.getFloat(0), background.getFloat(1), background.getFloat(2));

        JSONArray textColor = config.getJSONArray("textColor");
        Color4f color = new Color4f(textColor.getFloat(0), textColor.getFloat(1), textColor.getFloat(2), 1f);
        Vector2f windowSize = new Vector2f(mainContext.getWindow().getInfo().getVirtualSizeRef());

        // Fonts and shaders come from the batch "init", loaded for the whole game
        title = new Text();
        title.setFont("bahnschrift")
                .setFontSize(60)
                .setReference(EDirection.Up)
                .setAlignment(ETextAlignment.Center)
                .setPosition(new Vector2f(windowSize.x / 2, 30))
                .setColor(color)
                .setText(config.getString("title"));

        message = new Text();
        message.setFont("bahnschrift")
                .setFontSize(28)
                .setReference(EDirection.Up)
                .setAlignment(ETextAlignment.Center)
                .setPosition(new Vector2f(windowSize.x / 2, 120))
                .setColor(color)
                .setText(config.getString("message"));

        // One square per entry of the JSON. setMainTextureChannel takes the name of a TextureData: the renderer
        // asks GLResources for the GL texture and holds a reference on it until its unload
        float size = config.getFloat("squareSize");
        JSONArray squaresConfig = config.getJSONArray("squares");
        for (int i = 0; i < squaresConfig.length(); ++i) {
            JSONObject squareConfig = squaresConfig.getJSONObject(i);

            RectangleRenderer square = new RectangleRenderer("texture2D");
            square.setMainTextureChannel(squareConfig.getString("texture"));
            square.setSizePix(size, size);
            square.setPosition(new Vector2f(squareConfig.getFloat("x"), squareConfig.getFloat("y")));
            squares.add(square);
        }

        // Tweenings compute a value over time, updated in update(): here a full turn back and forth
        rotation = new FloatTweening();
        rotation.setTweeningOption(ETweeningOption.LoopReversed)
                .setTweeningValues(ETweeningType.Sinusoidal, ETweeningBehaviour.InOut)
                .initTwoValue(config.getFloat("rotationSeconds"), 0f, MightyMath.PI_FLOAT * 2f);
    }

    /*
     * Called at each tick (EngineConfig.setTps, 70 per second in the demo), only once the scene is launched:
     * the game logic goes here (inputs, movements, physics), never drawing.
     * Call super.update: it updates the objects added with addUpdatable.
     * The duration of a tick is GameTime.DeltaTime(); a scene change asked here happens at the start of the next tick.
     */
    @Override
    public void update() {
        super.update();

        // inputPressed: true only during the tick where the key goes down (getState: as long as it is held)
        if (mainContext.getInputManager().inputPressed(ActionId.ESCAPE)) {
            // The current scene is unloaded and released, then MenuScene is initialized
            sceneManagerInterface.setNewScene(new MenuScene(), new String[]{});
            return;
        }

        if (mainContext.getInputManager().inputPressed(ActionId.ENTER))
            rotationPaused = !rotationPaused;

        if (!rotationPaused)
            rotation.update();

        for (int i = 0; i < squares.size(); ++i) {
            // Opposite directions for the two squares
            squares.get(i).setRotationZ(i % 2 == 0 ? rotation.value() : -rotation.value());
        }
    }

    /*
     * Called at the end of each tick, after update: the engine uses it to reset the "pressed" and "released"
     * states of the inputs. Override it only for logic that must run after every update, and call super.
     */
    @Override
    public void postUpdate() {
        super.postUpdate();
    }

    /*
     * Called at each frame (EngineConfig.setFps), independently of the ticks: only drawing, no game logic.
     * The scene is drawn on a virtual framebuffer of the virtual size (1280x720 in the demo),
     * then scaled to the window by setAndDisplayRealScene.
     */
    @Override
    public void display() {
        setVirtualScene();
        clear();

        // Drawn in this order: the last ones are above
        for (RectangleRenderer square : squares)
            square.display();

        title.display();
        message.display();

        setAndDisplayRealScene();
    }

    /*
     * Called when the scene is left, ONLY if launch was called: free here what launch created.
     * Each renderer or text frees its GL objects (buffers, VAO) and its references on the shared textures:
     * a forgotten unload is a leak, found by the step "leakcheck DocumentationScene" of tools/scenario.py.
     * Call super.unload: it frees the virtual scene and the objects added with addUpdatable/addDisplayable.
     * The resources of the batches are not unloaded here: the engine removes the references of the batches itself.
     */
    @Override
    public void unload() {
        super.unload();

        title.unload();
        message.unload();

        for (RectangleRenderer square : squares)
            square.unload();
        squares.clear();
    }

    /*
     * Called when the scene is left, after unload, ALWAYS, even if the scene was left while loading
     * (launch and unload not called): free here what init created. No need to call super.release.
     * deleteResource removes the data added by init from Resources. Its GL texture, if it was sent,
     * is freed when its last user lets it go (the squares, already unloaded in unload).
     * Do not use objects created in launch here: they are null if the scene was left while loading.
     */
    @Override
    public void release() {
        resources.deleteResource(TextureData.class, GENERATED_TEXTURE);
    }
}
