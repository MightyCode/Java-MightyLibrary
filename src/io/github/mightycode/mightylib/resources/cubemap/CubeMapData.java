package io.github.mightycode.mightylib.resources.cubemap;

import io.github.mightycode.mightylib.graphics.GLElement;
import io.github.mightycode.mightylib.resources.MultiSourceDataType;
import org.lwjgl.stb.STBImage;

import java.nio.ByteBuffer;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * Six square pictures of the same size, the faces of a cube seen from inside (skybox, reflections), read from
 * resources/cubemaps/name/right|left|top|bottom|front|back.png (the order of GL_TEXTURE_CUBE_MAP_POSITIVE_X to
 * NEGATIVE_Z). Decoded by stb_image like the textures; its GL element is a CubeMapTexture.
 */
public class CubeMapData extends MultiSourceDataType {
    public static final int FACE_COUNT = 6;
    private static final String[] FACES = {"right", "left", "top", "bottom", "front", "back"};
    private static final String EXTENSION = ".png";

    // Decoded by the loader (worker), taken by internLoad; native memory of stb_image
    private final ByteBuffer[] decoded = new ByteBuffer[FACE_COUNT];
    private int decodedSize;
    private ByteBuffer[] faces = new ByteBuffer[FACE_COUNT];
    private int faceSize;
    // The faces are owned by stb_image (freed by it), or by the garbage collector (generated by the code)
    private boolean nativeFaces;

    // folder: the folder of the six files, ending with '/'
    CubeMapData(String name, String folder) {
        this(name, facePaths(folder));
    }

    // The fallback has no file (empty list)
    CubeMapData(String name, List<String> paths) {
        super(TYPE_SET_UP.THREAD_CONTEXT, name, paths);
    }

    // The file names of the faces, in order
    public static List<String> faceNames() {
        return Collections.unmodifiableList(Arrays.asList(FACES));
    }

    private static List<String> facePaths(String folder) {
        List<String> paths = new ArrayList<>();
        for (String face : FACES)
            paths.add(folder + face + EXTENSION);
        return paths;
    }

    // Loader (worker): the RGBA pixels of a face decoded by stb_image, taken over by this data
    synchronized void setDecodedFace(int index, ByteBuffer pixels, int size) {
        if (decoded[index] != null)
            STBImage.stbi_image_free(decoded[index]);
        decoded[index] = pixels;
        decodedSize = size;
    }

    // Size of the faces already decoded by the last reading, 0 before the first one
    synchronized int decodedSize() {
        return decodedSize;
    }

    // Loader: a face failed, the decoded ones are freed (the data is not preloaded, nothing else would free them)
    synchronized void freeDecoded() {
        for (int i = 0; i < FACE_COUNT; ++i) {
            if (decoded[i] != null) {
                STBImage.stbi_image_free(decoded[i]);
                decoded[i] = null;
            }
        }
        decodedSize = 0;
    }

    @Override
    protected synchronized boolean internLoad() {
        for (ByteBuffer face : decoded) {
            if (face == null)
                return false;
        }

        freeFaces();
        faces = decoded.clone();
        Arrays.fill(decoded, null);
        faceSize = decodedSize;
        nativeFaces = true;
        return true;
    }

    // For the data generated by the code (fallback): pixels left to the garbage collector
    protected final synchronized void setGeneratedFaces(ByteBuffer[] generated, int size) {
        freeFaces();
        faces = generated.clone();
        faceSize = size;
        nativeFaces = false;
    }

    @Override
    protected synchronized void internCancelPreload() {
        freeDecoded();
    }

    @Override
    protected synchronized void internUnload() {
        freeFaces();
    }

    private void freeFaces() {
        for (int i = 0; i < FACE_COUNT; ++i) {
            if (nativeFaces && faces[i] != null)
                STBImage.stbi_image_free(faces[i]);
            faces[i] = null;
        }
        faceSize = 0;
    }

    // RGBA pixels of the face (index in the order of faceNames), null until loaded
    public synchronized ByteBuffer getFace(int index) {
        return faces[index];
    }

    // Width and height of each face, 0 until loaded
    public synchronized int getFaceSize() {
        return faceSize;
    }

    @Override
    public long estimatedCpuBytes() {
        int size = getFaceSize();
        return size > 0 ? (long) FACE_COUNT * size * size * 4 : super.estimatedCpuBytes() * 4;
    }

    @Override
    public long estimatedGpuBytes() {
        return estimatedCpuBytes();
    }

    @Override
    public Class<? extends GLElement> glElementType() {
        return CubeMapTexture.class;
    }

    @Override
    public GLElement createGLElement() {
        return new CubeMapTexture(this);
    }
}
