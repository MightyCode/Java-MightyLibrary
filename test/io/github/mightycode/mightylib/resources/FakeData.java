package io.github.mightycode.mightylib.resources;

import java.util.concurrent.atomic.AtomicInteger;

/**
 * Resource without file nor GL: counts its loads and unloads and records any inconsistency
 * (loaded twice, unloaded while not loaded, loaded before a dependency, loaded on a wrong thread).
 */
public class FakeData extends DataType {
    // Shared with the reload copies: counted for the data, whatever the instance
    final AtomicInteger loads;
    final AtomicInteger unloads;
    final AtomicInteger preloads;
    final AtomicInteger errors;

    private volatile boolean live;

    // Read in the preload step, set by the test (on the data, read by its reload copies)
    volatile int preloadMilliseconds;
    volatile boolean failLoad;
    // Thrown by the preload step when set
    volatile RuntimeException preloadThrows;
    volatile FakeData dependencyToAdd;
    // Supports reload copies (hot reload apart), true by default
    volatile boolean reloadApart = true;
    // Generated by the code: no file to read again
    volatile boolean generated;
    // Number of internLoad calls needed to load (a load in several steps, like a shader), 1 by default
    volatile int loadSteps = 1;
    // Called in each load step with the number of steps run so far
    volatile java.util.function.IntConsumer duringLoadStep;
    // Load steps run in total (all calls), shared with the reload copies
    final AtomicInteger loadStepCalls;
    private int stepsDone;

    @Override
    public boolean hasSource() {
        return !settings.generated;
    }

    // File watched for hot reload (null: none), set by the test
    volatile String sourcePath;

    // Second file of the data (a description and its source), set by the test
    volatile String extraSourcePath;

    @Override
    public java.util.List<String> sourcePaths() {
        String path = settings.sourcePath;
        if (path == null)
            return java.util.Collections.emptyList();

        String extra = settings.extraSourcePath;
        return extra == null ? java.util.Collections.singletonList(path) : java.util.Arrays.asList(path, extra);
    }

    // Content: the number of the preload that read it, exchanged on reload
    private volatile int content;
    private volatile int readContent;

    private final FakeData settings;
    private volatile Thread mainThread;

    public FakeData(TYPE_SET_UP typeSetUp, String name) {
        super(typeSetUp, name);
        loads = new AtomicInteger();
        unloads = new AtomicInteger();
        preloads = new AtomicInteger();
        errors = new AtomicInteger();
        loadStepCalls = new AtomicInteger();
        settings = this;
    }

    private FakeData(FakeData original) {
        super(original.getTypeSetUp(), original.getDataName());
        loads = original.loads;
        unloads = original.unloads;
        preloads = original.preloads;
        errors = original.errors;
        loadStepCalls = original.loadStepCalls;
        settings = original;
        mainThread = original.mainThread;
    }

    @Override
    protected DataType createReloadCopy() {
        return settings.reloadApart ? new FakeData(settings) : null;
    }

    @Override
    protected void swapContent(DataType copy) {
        FakeData other = (FakeData) copy;
        int previous = content;
        content = other.content;
        other.content = previous;
    }

    // 0 when not loaded
    int content() {
        return content;
    }

    // Main context data must be loaded on this thread
    FakeData expectMainThread(Thread thread) {
        mainThread = thread;
        return this;
    }

    void preloadStep() {
        if (getTypeSetUp() == TYPE_SET_UP.THREAD_PRELOAD_MAIN_LOAD && Thread.currentThread() == mainThread)
            error("preloaded on the main thread");

        readContent = preloads.incrementAndGet();
        if (settings.preloadThrows != null)
            throw settings.preloadThrows;

        // A long read with a checkpoint every few milliseconds
        long end = System.currentTimeMillis() + settings.preloadMilliseconds;
        while (System.currentTimeMillis() < end) {
            checkCancelled();
            try {
                Thread.sleep(2);
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
            }
        }

        FakeData dependency = settings.dependencyToAdd;
        if (dependency != null)
            addDependency(dependency);
    }

    @Override
    protected boolean internLoad() {
        if (live)
            error("loaded twice");

        // A failed dependency is replaced by its fallback
        for (DataType dependency : getDependencies()) {
            if (!dependency.isLoaded() && !dependency.failed)
                error("loaded before its dependency " + dependency.getDataName());
        }

        if (mainThread != null && Thread.currentThread() != mainThread)
            error("loaded on " + Thread.currentThread().getName());

        if (settings.failLoad)
            return false;

        int call = loadStepCalls.incrementAndGet();
        if (settings.duringLoadStep != null)
            settings.duringLoadStep.accept(call);

        if (++stepsDone < settings.loadSteps)
            return true;

        live = true;
        content = readContent;
        loads.incrementAndGet();
        return true;
    }

    @Override
    protected boolean loadContinues() {
        return stepsDone < settings.loadSteps;
    }

    // Left in the middle of a load in steps: what the steps made is released
    @Override
    protected void internCancelPreload() {
        stepsDone = 0;
    }

    @Override
    protected void internUnload() {
        if (!live)
            error("unloaded while not loaded");

        stepsDone = 0;
        live = false;
        content = 0;
        unloads.incrementAndGet();
    }

    private void error(String message) {
        errors.incrementAndGet();
        System.err.println("--FakeData " + getDataName() + ": " + message);
    }

    int referenceCount() {
        return references.size();
    }
}
